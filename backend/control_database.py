def _movement_payload(row: dict[str, Any]) -> dict[str, Any]:
    """Converte um movimento para JSON sem perder precisão.

    `Decimal` vira texto (não float: o razão trabalha em decimal exato) e a
    data vira ISO. O processo filho refaz os dois tipos antes de gravar.
    """
    occurred_at = row["occurred_at"]
    return {
        "source_key": row["source_key"],
        "sequence": int(row["sequence"]),
        "movement_type": row["movement_type"],
        "process": row["process"],
        "next_process": row.get("next_process"),
        "material_lot_id": row.get("material_lot_id"),
        "production_lot_id": row.get("production_lot_id"),
        "origin_type": row.get("origin_type"),
        "good_pieces": str(row.get("good_pieces") or 0),
        "loss_pieces": str(row.get("loss_pieces") or 0),
        "consumed_kg": str(row.get("consumed_kg") or 0),
        "machine": row.get("machine"),
        "operator": row.get("operator"),
        "shift": row.get("shift"),
        "reason": row.get("reason"),
        "occurred_at": occurred_at.isoformat() if hasattr(occurred_at, "isoformat") else str(occurred_at),
    }


def _restore_movement(row: dict[str, Any]) -> dict[str, Any]:
    return {
        **row,
        "good_pieces": Decimal(row["good_pieces"]),
        "loss_pieces": Decimal(row["loss_pieces"]),
        "consumed_kg": Decimal(row["consumed_kg"]),
        "occurred_at": datetime.fromisoformat(row["occurred_at"]),
    }


def record_movements(product_id: str, movements: list[dict[str, Any]]) -> int:
    """Acrescenta ao histórico, sem nunca alterar o que já está gravado."""
    try:
        return _record_movements_native(product_id, movements)
    except ImportError:
        if not movements:
            return 0
        # Por arquivo, não por argumento: no Windows a linha de comando estoura
        # em ~32 KB e um dia de apontamentos passa disso com folga.
        handle = tempfile.NamedTemporaryFile(
            "w", suffix=".json", delete=False, encoding="utf-8"
        )
        try:
            json.dump(
                {"product_id": product_id, "movements": [_movement_payload(row) for row in movements]},
                handle,
                ensure_ascii=False,
            )
            handle.close()
            return int(_fallback("movements-record", {"path": handle.name}, timeout=120))
        finally:
            handle.close()
            try:
                os.unlink(handle.name)
            except OSError:
                pass


