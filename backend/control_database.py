def _driver():
    try:
        import psycopg  # type: ignore
        return psycopg
    except ImportError:
        import psycopg2  # type: ignore
        return psycopg2


@contextmanager
def _connection() -> Iterator[Any]:
    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        raise RuntimeError("DATABASE_URL não configurada")
    connection = _driver().connect(database_url, connect_timeout=10, sslmode="require")
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


_SCHEMA_READY = False


def _ensure_control_schema_native(force: bool = False) -> None:
    """Garante o schema do controle uma vez por processo.

    O DDL é idempotente, mas executá-lo a cada listagem custava uma conexão e
    dezenas de comandos por requisição. `force=True` mantém a verificação real
    usada por `GET /api/readiness`.
    """
    global _SCHEMA_READY
    if _SCHEMA_READY and not force:
        return
    with _connection() as connection, connection.cursor() as cursor:
        cursor.execute("CREATE SCHEMA IF NOT EXISTS flow_control")
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS flow_control.opening_inventory (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference_date date NOT NULL,
                product_id varchar(80) NOT NULL,
                product_name varchar(160) NOT NULL,
                process varchar(120) NOT NULL,
                position_status varchar(24) NOT NULL DEFAULT 'waiting',
                piece_quantity numeric(18,3) NOT NULL DEFAULT 0,
                rod_kg_in_process numeric(18,3),
                operator_name varchar(160),
                notes text,
                updated_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT opening_inventory_position_key UNIQUE (reference_date, product_id, process, position_status)
            )
        """)
        cursor.execute("ALTER TABLE flow_control.opening_inventory ADD COLUMN IF NOT EXISTS position_status varchar(24) NOT NULL DEFAULT 'waiting'")
        cursor.execute("ALTER TABLE flow_control.opening_inventory ALTER COLUMN rod_kg_in_process DROP NOT NULL")
        cursor.execute("ALTER TABLE flow_control.opening_inventory DROP CONSTRAINT IF EXISTS opening_inventory_reference_date_product_id_key")
        cursor.execute("ALTER TABLE flow_control.opening_inventory DROP CONSTRAINT IF EXISTS opening_inventory_position_status_check")
        cursor.execute("ALTER TABLE flow_control.opening_inventory ADD CONSTRAINT opening_inventory_position_status_check CHECK (position_status IN ('waiting', 'in_process', 'completed'))")
        cursor.execute("CREATE UNIQUE INDEX IF NOT EXISTS opening_inventory_position_key_idx ON flow_control.opening_inventory(reference_date, product_id, process, position_status)")
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS flow_control.material_lots (
                lot_id varchar(120) PRIMARY KEY,
                product_id varchar(80) NOT NULL,
                rod_code varchar(40) NOT NULL,
                destination_code varchar(80),
                source_document varchar(40),
                source_record bigint,
                transfer_date date NOT NULL,
                initial_kg numeric(18,3) NOT NULL,
                balance_kg numeric(18,3) NOT NULL,
                status varchar(20) NOT NULL DEFAULT 'closed',
                source_key varchar(180) NOT NULL UNIQUE,
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now()
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS flow_control.lot_movements (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                lot_id varchar(120) NOT NULL REFERENCES flow_control.material_lots(lot_id),
                movement_type varchar(24) NOT NULL,
                quantity_kg numeric(18,3) NOT NULL,
                piece_quantity numeric(18,3),
                process varchar(120),
                source_key varchar(180) UNIQUE,
                notes text,
                occurred_at timestamptz NOT NULL DEFAULT now()
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS flow_control.production_lots (
                lot_id varchar(120) PRIMARY KEY,
                product_id varchar(80) NOT NULL,
                product_name varchar(160) NOT NULL,
                material_lot_id varchar(120),
                origin_type varchar(32) NOT NULL DEFAULT 'material',
                route_key varchar(80),
                previous_process varchar(120),
                current_process varchar(120) NOT NULL,
                quantity_pieces numeric(18,3) NOT NULL DEFAULT 0,
                rod_kg numeric(18,3) NOT NULL DEFAULT 0,
                status varchar(24) NOT NULL DEFAULT 'waiting',
                hold_reason text,
                operator_name varchar(160),
                waiting_since timestamptz NOT NULL DEFAULT now(),
                started_at timestamptz,
                updated_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT production_lots_status_check CHECK (status IN ('waiting', 'awaiting_next', 'in_process', 'guarded', 'completed'))
            )
        """)
        cursor.execute("ALTER TABLE flow_control.production_lots ADD COLUMN IF NOT EXISTS previous_process varchar(120)")
        cursor.execute("ALTER TABLE flow_control.production_lots ADD COLUMN IF NOT EXISTS origin_type varchar(32) NOT NULL DEFAULT 'material'")
        cursor.execute("ALTER TABLE flow_control.production_lots ADD COLUMN IF NOT EXISTS route_key varchar(80)")
        cursor.execute("ALTER TABLE flow_control.production_lots DROP CONSTRAINT IF EXISTS production_lots_status_check")
        cursor.execute("ALTER TABLE flow_control.production_lots ADD CONSTRAINT production_lots_status_check CHECK (status IN ('waiting', 'awaiting_next', 'in_process', 'guarded', 'completed'))")
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS flow_control.production_lot_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                lot_id varchar(120) NOT NULL REFERENCES flow_control.production_lots(lot_id),
                event_type varchar(32) NOT NULL,
                from_status varchar(24),
                to_status varchar(24) NOT NULL,
                process varchar(120) NOT NULL,
                operator_name varchar(160),
                reason text,
                source_key varchar(180),
                good_pieces numeric(18,3) NOT NULL DEFAULT 0,
                loss_pieces numeric(18,3) NOT NULL DEFAULT 0,
                quantity_kg numeric(18,6),
                from_process varchar(120),
                to_process varchar(120),
                calculation_method varchar(32),
                occurred_at timestamptz NOT NULL DEFAULT now()
            )
        """)
        cursor.execute("ALTER TABLE flow_control.production_lot_events ADD COLUMN IF NOT EXISTS source_key varchar(180)")
        cursor.execute("ALTER TABLE flow_control.production_lot_events ADD COLUMN IF NOT EXISTS good_pieces numeric(18,3) NOT NULL DEFAULT 0")
        cursor.execute("ALTER TABLE flow_control.production_lot_events ADD COLUMN IF NOT EXISTS loss_pieces numeric(18,3) NOT NULL DEFAULT 0")
        cursor.execute("ALTER TABLE flow_control.production_lot_events ADD COLUMN IF NOT EXISTS quantity_kg numeric(18,6)")
        cursor.execute("ALTER TABLE flow_control.production_lot_events ADD COLUMN IF NOT EXISTS from_process varchar(120)")
        cursor.execute("ALTER TABLE flow_control.production_lot_events ADD COLUMN IF NOT EXISTS to_process varchar(120)")
        cursor.execute("ALTER TABLE flow_control.production_lot_events ADD COLUMN IF NOT EXISTS calculation_method varchar(32)")
        cursor.execute("CREATE UNIQUE INDEX IF NOT EXISTS production_lot_events_source_key_idx ON flow_control.production_lot_events(source_key) WHERE source_key IS NOT NULL")
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS flow_control.movement_ledger (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id varchar(80) NOT NULL,
                source_key varchar(180) NOT NULL,
                sequence integer NOT NULL,
                movement_type varchar(32) NOT NULL,
                process varchar(120) NOT NULL,
                next_process varchar(120),
                material_lot_id varchar(120),
                production_lot_id varchar(120),
                origin_type varchar(32),
                good_pieces numeric(18,3) NOT NULL DEFAULT 0,
                loss_pieces numeric(18,3) NOT NULL DEFAULT 0,
                consumed_kg numeric(18,6) NOT NULL DEFAULT 0,
                machine varchar(120),
                operator_name varchar(160),
                shift varchar(24),
                reason text,
                occurred_at timestamptz NOT NULL,
                recorded_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT movement_ledger_identity UNIQUE (product_id, source_key, sequence)
            )
        """)
        cursor.execute(
            "CREATE INDEX IF NOT EXISTS movement_ledger_product_time_idx"
            " ON flow_control.movement_ledger(product_id, occurred_at DESC, id DESC)"
        )
        cursor.execute(
            "CREATE INDEX IF NOT EXISTS movement_ledger_material_lot_idx"
            " ON flow_control.movement_ledger(material_lot_id) WHERE material_lot_id IS NOT NULL"
        )
        # Imutabilidade cobrada pelo banco, não por convenção: a aplicação
        # nunca emite UPDATE nem DELETE aqui, mas convenção não sobrevive à
        # próxima pessoa com um console aberto. Correção é linha nova.
        cursor.execute("""
            CREATE OR REPLACE FUNCTION flow_control.movement_ledger_append_only()
            RETURNS trigger AS $$
            BEGIN
                RAISE EXCEPTION
                    'flow_control.movement_ledger é somente-inserção: % recusado',
                    TG_OP;
            END;
            $$ LANGUAGE plpgsql
        """)
        cursor.execute("DROP TRIGGER IF EXISTS movement_ledger_no_update ON flow_control.movement_ledger")
        cursor.execute("""
            CREATE TRIGGER movement_ledger_no_update
            BEFORE UPDATE OR DELETE ON flow_control.movement_ledger
            FOR EACH ROW EXECUTE FUNCTION flow_control.movement_ledger_append_only()
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS flow_control.traceability_unmatched (
                source_key varchar(180) PRIMARY KEY,
                product_id varchar(80) NOT NULL,
                process varchar(120) NOT NULL,
                machine varchar(120),
                good_pieces numeric(18,3) NOT NULL,
                loss_pieces numeric(18,3) NOT NULL,
                reason text NOT NULL,
                occurred_at timestamptz NOT NULL,
                resolved_at timestamptz
            )
        """)
    _SCHEMA_READY = True


def _list_opening_inventory_native(reference_date: date) -> list[dict[str, Any]]:
    _ensure_control_schema_native()
    with _connection() as connection, connection.cursor() as cursor:
        cursor.execute("""
            SELECT product_id, product_name, process, position_status, piece_quantity,
                   rod_kg_in_process, operator_name, notes, updated_at, reference_date
            FROM flow_control.opening_inventory
            WHERE reference_date = %s
            ORDER BY product_name
        """, (reference_date,))
        rows = cursor.fetchall()
    return [
        {
            "product_id": row[0], "product_name": row[1], "process": row[2],
            "position_status": row[3], "piece_quantity": float(row[4]), "rod_kg_in_process": float(row[5]) if row[5] is not None else None,
            "operator_name": row[6] or "", "notes": row[7] or "",
            "updated_at": row[8].isoformat() if row[8] else None,
            "reference_date": row[9].isoformat() if row[9] else None,
        }
        for row in rows
    ]


def _save_opening_inventory_native(reference_date: date, product: dict[str, Any], payload: dict[str, Any]) -> dict[str, Any]:
    _ensure_control_schema_native()
    with _connection() as connection, connection.cursor() as cursor:
        cursor.execute("""
            INSERT INTO flow_control.opening_inventory
                (reference_date, product_id, product_name, process, position_status, piece_quantity,
                 rod_kg_in_process, operator_name, notes, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, now())
            ON CONFLICT (reference_date, product_id, process, position_status) DO UPDATE SET
                product_name = EXCLUDED.product_name,
                process = EXCLUDED.process,
                piece_quantity = EXCLUDED.piece_quantity,
                rod_kg_in_process = EXCLUDED.rod_kg_in_process,
                operator_name = EXCLUDED.operator_name,
                notes = EXCLUDED.notes,
                updated_at = now()
            RETURNING updated_at
        """, (
            reference_date, product["id"], product["name"], payload["process"], payload.get("position_status", "waiting"),
            payload["piece_quantity"], payload["rod_kg_in_process"],
            payload.get("operator_name") or None, payload.get("notes") or None,
        ))
        updated_at = cursor.fetchone()[0]
    return {"status": "saved", "product_id": product["id"], "updated_at": updated_at.isoformat()}


def _classify_opening_inventory_native(
    reference_date: date, positions: list[dict[str, str]]
) -> int:
    _ensure_control_schema_native()
    updated = 0
    with _connection() as connection, connection.cursor() as cursor:
        for position in positions:
            cursor.execute(
                """UPDATE flow_control.opening_inventory
                   SET position_status = 'completed', updated_at = now(),
                       notes = concat_ws(' ', nullif(notes, ''),
                           'Classificado como concluído conforme regra operacional informada.')
                   WHERE reference_date = %s AND product_id = %s AND process = %s
                     AND position_status = 'waiting'""",
                (reference_date, position["product_id"], position["process"]),
            )
            updated += cursor.rowcount
    return updated


def _sync_material_lots_native(product_id: str, lots: list[dict[str, Any]]) -> int:
    if not lots:
        return 0
    _ensure_control_schema_native()
    synced = 0
    with _connection() as connection, connection.cursor() as cursor:
        for lot in lots:
            transfer_date = date.fromisoformat("-".join(reversed(lot["date"].split("/"))))
            source_key = f'TOTVS:SD3010:{lot["material_code"]}:{lot["document"]}:{lot["id"]}'
            cursor.execute("""
                INSERT INTO flow_control.material_lots
                    (lot_id, product_id, rod_code, destination_code, source_document,
                     source_record, transfer_date, initial_kg, balance_kg, status, source_key)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, 'closed', %s)
                ON CONFLICT (source_key) DO NOTHING
            """, (
                lot["id"], product_id, lot["material_code"], lot["destination"],
                lot["document"], lot.get("source_record"), transfer_date,
                lot["initial_kg"], lot["initial_kg"], source_key,
            ))
            synced += cursor.rowcount
    return synced


